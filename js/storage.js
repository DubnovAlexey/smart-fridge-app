const STORAGE_KEY = 'smart_fridge_data';

// ------------------------------------------------------------------------------
// 1. ФУНКЦИЯ СОХРАНЕНИЯ ДАННЫХ
// Слово "export" делает эту функцию доступной для других файлов.
// В скобках мы принимаем "fridgeArray" — массив наших продуктов, который нужно сохранить.
// ------------------------------------------------------------------------------
export function saveFridgeData(fridgeArray) {

    // LocalStorage не понимает сложные массивы.
    // Поэтому мы используем JSON.stringify, чтобы превратить наш массив в длинную текстовую строку.
    const stringData = JSON.stringify(fridgeArray);

    // Обращаемся к браузеру: localStorage.setItem(КЛЮЧ, ДАННЫЕ).
    // Мы говорим: "Сохрани текст (stringData) в сейф под названием (STORAGE_KEY)".
    localStorage.setItem(STORAGE_KEY, stringData);
}


// ------------------------------------------------------------------------------
// 2. ФУНКЦИЯ ЗАГРУЗКИ ДАННЫХ
// Эта функция ничего не принимает в скобках, потому что ее задача — просто достать данные из браузера.
// ------------------------------------------------------------------------------
export function loadFridgeData() {

    // Обращаемся к браузеру: localStorage.getItem(КЛЮЧ).
    // Мы говорим: "Достань мне текст, который лежит в сейфе под названием (STORAGE_KEY)".
    const stringData = localStorage.getItem(STORAGE_KEY);

    // Условие (ЕСЛИ): Оператор "!" означает "НЕ".
    // Если НЕ stringData (то есть там пусто, null, мы открыли программу впервые).
    if (!stringData) {
        // Раз данных нет, мы возвращаем абсолютно пустой массив []. Холодильник пуст.
        return [];
    }

    // Если программа дошла сюда, значит текст в сейфе есть.
    // Мы используем JSON.parse, чтобы превратить обычный текст обратно в умный JavaScript-массив.
    // И сразу возвращаем (return) этот массив туда, кто его запросил.
    return JSON.parse(stringData);
}