// Слово "import" означает, что мы забираем (импортируем) инструменты из других файлов.
// Мы берем функции загрузки (load) и сохранения (save) из нашего "сейфа" (storage.js).
import { loadFridgeData, saveFridgeData } from '../storage.js';

// Слово "class" (Класс) — это чертеж или шаблон нашего холодильника.
// Слово "export" позволяет главному файлу (app.js) использовать этот чертеж.
export class FridgeModel {

    // "constructor" — это функция, которая срабатывает автоматически ровно в тот момент,
    // когда мы включаем программу (создаем объект холодильника).
    constructor() {
        // "this" (этот) означает, что переменная "batches" (партии) принадлежит именно этому холодильнику.
        // При включении программы мы сразу достаем все сохраненные продукты из сейфа.
        this.batches = loadFridgeData();
    }

    // ------------------------------------------------------------------------------
    // МЕТОД 1: Добавление новой партии продукта
    // ------------------------------------------------------------------------------
    addBatch(name, category, count, unit, daysValid, isPerishable, isFrozen, price, note) {

        // Date.now() — это важнейшая команда! Она выдает текущее реальное время
        // в миллисекундах (Timestamp), прошедших с 1 января 1970 года.
        // Это позволяет нам не зависеть от того, включен компьютер или нет.
        const now = Date.now();

        // В одних сутках 24 часа, в часе 60 минут, в минуте 60 секунд, в секунде 1000 миллисекунд.
        // Перемножаем это всё и получаем количество миллисекунд в одном дне (86 400 000).
        const msInDay = 24 * 60 * 60 * 1000;

        // Считаем дату "смерти" продукта: текущее время ПЛЮС (количество дней годности УМНОЖЕННОЕ на миллисекунды в дне).
        const expirationDate = now + (daysValid * msInDay);

        // Создаем Объект (коробку с данными) для новой партии продукта.
        const newBatch = {
            id: Date.now().toString(), // Даем уникальный номер (ID) на основе текущей миллисекунды
            name: name,
            category: category,
            count: parseFloat(count),  // parseFloat превращает текст "1.5" в дробное математическое число 1.5
            unit: unit,
            addedAt: now,              // Запоминаем время, когда положили в холодильник
            expirationDate: expirationDate, // Запоминаем точное время, когда испортится
            isPerishable: isPerishable, // Галочка "Скоропортящееся" (true/false - да/нет)
            isFrozen: isFrozen,         // Галочка "В морозилке" (true/false)
            price: parseFloat(price) || 0, // Если цену не ввели, ставим 0
            note: note                 // Заметка (например, "Купил в Пятерочке")
        };

        // Команда "push" (затолкать) добавляет нашу новую коробку (newBatch) в общий массив холодильника (this.batches).
        this.batches.push(newBatch);

        // Вызываем функцию сохранения из storage.js, чтобы записать обновленный массив в память браузера.
        saveFridgeData(this.batches);
    }

    // ------------------------------------------------------------------------------
    // МЕТОД 2: Получение всех продуктов с пересчитанным сроком годности на СЕГОДНЯ
    // ------------------------------------------------------------------------------
    getProcessedBatches() {
        const now = Date.now();
        const msInDay = 24 * 60 * 60 * 1000;

        // Команда "map" (преобразовать/перебрать) проходит по каждому продукту в массиве по очереди
        // и позволяет нам изменить его данные перед тем, как отдать на экран.
        const processed = this.batches.map(batch => {

            // Если стоит галочка "В морозилке", продукт не портится!
            // Возвращаем (return) продукт, в котором жестко прописано, что осталось 999 дней.
            // Троеточие (...batch) означает "скопируй всё, что было в этом объекте".
            if (batch.isFrozen) {
                return { ...batch, daysLeft: 999 };
            }

            // Высчитываем разницу в миллисекундах: Дата смерти МИНУС текущее время.
            const diffMs = batch.expirationDate - now;

            // Делим разницу на количество миллисекунд в дне.
            // Math.ceil() округляет число всегда в большую сторону (например, 2.1 дня превратится в 3 дня).
            const daysLeft = Math.ceil(diffMs / msInDay);

            // Возвращаем копию продукта, в которую добавили новое свойство: daysLeft (осталось дней).
            return { ...batch, daysLeft: daysLeft };
        });

        // Команда "sort" сортирует наш массив.
        // (a, b) => a.daysLeft - b.daysLeft означает:
        // "Сравни два продукта. У кого осталось меньше дней (например, 1 день против 5 дней), тот встанет ВЫШЕ в списке".
        return processed.sort((a, b) => a.daysLeft - b.daysLeft);
    }
}