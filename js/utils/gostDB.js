export function guessExpirationDays(name, category) {
    if (!name) return '';
    const lowerName = name.toLowerCase();

    // Если категория не выбрана, берем "Прочее" (other)
    const catDB = GOST_DB[category];
    if (!catDB) return '';

    // Ищем точное совпадение по ключевому слову (включая части слов)
    for (const [keyword, days] of Object.entries(catDB.keywords)) {
        if (lowerName.includes(keyword)) {
            return days;
        }
    }

    // Если не нашли специфическое слово, отдаем дефолтное значение для этой категории
    return catDB.default;
}