// Слово "export" (экспорт) означает, что мы разрешаем другим файлам использовать эту функцию.
// Слово "function" (функция) означает, что мы создаем мини-завод.
// Название нашего завода - "validateProductData" (проверить данные продукта).
// В скобках (name, count, days) указаны "материалы", которые мы передаем на этот завод для проверки.
export function validateProductData(name, count, days) {

    // 1. ПРОВЕРКА НАЗВАНИЯ (name)
    // Условие "if" переводится как "ЕСЛИ".
    // Оператор "!" перед name означает "НЕ". То есть "если НЕ name" (если имя пустое или его вообще нет).
    // Функция ".trim()" обрезает лишние пробелы. Если пользователь ввел просто пробелы ("   "),
    // trim() сделает из этого пустоту (""), а мы проверим, равно ли это пустоте (=== "").
    // Знак "||" означает "ИЛИ".
    if (!name || name.trim() === '') {
        // Слово "return" (вернуть) — это то, что наш завод выдает в качестве результата и сразу останавливает работу.
        // Мы возвращаем Объект (в фигурных скобках {}). В нем говорим, что данные невалидны (valid: false).
        return { valid: false, error: 'Название продукта не может быть пустым.' };
    }

    // 2. ПРОВЕРКА КОЛИЧЕСТВА (count)
    // Мы проверяем: ЕСЛИ количество меньше или равно нулю (count <= 0)
    // ИЛИ (||) если это вообще не число (isNaN - is Not a Number).
    if (count <= 0 || isNaN(count)) {
        // Возвращаем объект с ошибкой, если количество неправильное.
        return { valid: false, error: 'Количество должно быть больше нуля.' };
    }

    // 3. ПРОВЕРКА СРОКА ГОДНОСТИ (days)
    // Срок годности не может быть отрицательным (меньше 0), но может быть 0 (испортится сегодня).
    if (days < 0 || isNaN(days)) {
        // Возвращаем ошибку.
        return { valid: false, error: 'Срок годности не может быть отрицательным.' };
    }

    // 4. УСПЕШНЫЙ РЕЗУЛЬТАТ
    // Если программа дошла до этой строчки, значит ни один "if" (ЕСЛИ) не сработал.
    // Значит, данные идеальные! Возвращаем ответ, что фейс-контроль пройден (valid: true).
    return { valid: true };
}


// Вторая функция-помощник. Она определяет цвет бейджика в зависимости от того, сколько дней осталось.
// Мы тоже ставим "export", чтобы ее можно было использовать в главном файле.
export function getStatusBadge(daysLeft) {

    // Если дней меньше 0 (продукт просрочен)
    if (daysLeft < 0) {
        // Возвращаем текст и классы красного цвета (Tailwind CSS)
        return { text: 'Просрочено', classes: 'bg-red-100 text-red-700 border-red-200' };
    }

    // Если дней осталось 3 или меньше (Желтая зона)
    if (daysLeft <= 3) {
        // Возвращаем текст с количеством дней и желтые классы
        return { text: `Осталось дней: ${daysLeft}`, classes: 'bg-yellow-100 text-yellow-800 border-yellow-300' };
    }

    // Во всех остальных случаях (если дней больше 3) — Зеленая зона
    return { text: `Осталось дней: ${daysLeft}`, classes: 'bg-green-100 text-green-700 border-green-200' };
}